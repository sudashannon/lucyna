const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', {
  getPet:()=>ipcRenderer.invoke('pet:get'),
  savePet:patch=>ipcRenderer.invoke('pet:settings',patch),
  resetPetPosition:()=>ipcRenderer.invoke('pet:reset-position'),
  petContext:context=>ipcRenderer.invoke('pet:context',context),
  onPetNavigate:fn=>{const listener=(_event,data)=>fn(data);ipcRenderer.on('pet:navigate',listener);return()=>ipcRenderer.removeListener('pet:navigate',listener);},
  getSettings: () => ipcRenderer.invoke('settings:get'),
  checkSettings: settings => ipcRenderer.invoke('settings:check', settings),
  saveSettings: settings => ipcRenderer.invoke('settings:save', settings),
  listWorks: () => ipcRenderer.invoke('works:list'),
  copyText: text => ipcRenderer.invoke('clipboard:write-text', text),
  readWork: root => ipcRenderer.invoke('work:read', root),
  context: query => ipcRenderer.invoke('stele:context', query),
  knowledgeCatalog: (refresh = false) => ipcRenderer.invoke('stele:knowledge', 'catalog', {refresh}),
  knowledgeDocument: id => ipcRenderer.invoke('stele:knowledge', 'document', {id}),
  knowledgeCandidates: () => ipcRenderer.invoke('stele:knowledge', 'candidates'),
  knowledgeReviews: () => ipcRenderer.invoke('stele:knowledge', 'reviews'),
  knowledgeImage: (id, src) => ipcRenderer.invoke('stele:knowledge', 'image', {id, src}),
  knowledgeRequest: (kind,args={}) => ipcRenderer.invoke('stele:knowledge',kind,args),
  knowledgeSaveFile: (name,bytes) => ipcRenderer.invoke('stele:save-file',name,bytes),
  onKnowledge: fn => {const listener=(_event,data)=>fn(data);ipcRenderer.on('stele:knowledge-event',listener);return()=>ipcRenderer.removeListener('stele:knowledge-event',listener);},
  start: options => ipcRenderer.invoke('omp:start', options),
  request: (type, data = {}, id) => ipcRenderer.invoke('omp:request', type, data, id),
  respond: (data,id) => ipcRenderer.invoke('omp:ui-response', data,id),
  close: id => ipcRenderer.invoke('omp:close',id),
  listConnections: () => ipcRenderer.invoke('omp:list'),
  chooseSession: () => ipcRenderer.invoke('session:choose'),
  listHistory: root => ipcRenderer.invoke('session:list', root),
  importSession: (source, root) => ipcRenderer.invoke('session:import', source, root),
  terminal: root => ipcRenderer.invoke('terminal:open', root),
  startTerminal: (root, dimensions) => ipcRenderer.invoke('terminal:start', root, dimensions),
  terminalInput: (id, data) => ipcRenderer.invoke('terminal:input', id, data),
  terminalResize: (id, cols, rows) => ipcRenderer.invoke('terminal:resize', id, cols, rows),
  closeTerminal: id => ipcRenderer.invoke('terminal:close', id),
  onTerminal: fn => { const listener = (_event, data) => fn(data); ipcRenderer.on('terminal:event', listener); return () => ipcRenderer.removeListener('terminal:event', listener); },
  choosePreview: root => ipcRenderer.invoke('preview:choose-file', root),
  readPreview: (root, reference, basePath) => ipcRenderer.invoke('preview:read', root, reference, basePath),
  listFiles: (root, directory, options) => ipcRenderer.invoke('preview:list', root, directory, options),
  webPreview: url => ipcRenderer.invoke('web:preview', url),
  onEvent: fn => { const listener = (_event, data) => fn(data); ipcRenderer.on('omp:event', listener); return () => ipcRenderer.removeListener('omp:event', listener); }
});
